        function sendAIChat() {
            const input = document.getElementById('ai-input');
            const history = document.getElementById('ai-history');
            const text = input.value.trim();

            if (!text) return;

            const userBubble = document.createElement('div');
            userBubble.className = "bg-keratonGold-500 text-teak-950 font-bold p-3 rounded-xl max-w-[85%] ml-auto text-xs";
            userBubble.textContent = text;
            history.appendChild(userBubble);

            input.value = '';
            history.scrollTop = history.scrollHeight;

            setTimeout(() => {
                const aiBubble = document.createElement('div');
                aiBubble.className = "bg-teak-900 p-3 rounded-xl border border-teak-800 text-teak-200 max-w-[85%] text-xs space-y-1";
                
                if (text.toLowerCase().includes('posisi') || text.toLowerCase().includes('fengshui') || text.toLowerCase().includes('arah')) {
                    aiBubble.innerHTML = "Secara tradisi Jawa (Primbon Arsitektur), pintu utama rumah Joglo idealnya menghadap ke **Selatan** (menghadap Samudera) atau **Utara** (menghadap Gunung) untuk aliran energi alami yang sejuk.";
                } else if (text.toLowerCase().includes('bedas') || text.toLowerCase().includes('limasan')) {
                    aiBubble.innerHTML = "<strong>Joglo</strong> menggunakan struktur Atap Tumpang Sari dengan 4 Soko Guru utama (untuk pendopo/hunian mewah), sedangkan <strong>Limasan</strong> beratap limas melandai ramah angin (sangat cocok untuk rumah tinggal modern).";
                } else {
                    aiBubble.innerHTML = "Matur nuwun telah bertanya! Ki Arsitek siap membantu estimasi biaya kayu jati, konsultasi denah pendopo, atau jadwal kunjungan survei lahan.";
                }

                history.appendChild(aiBubble);
                history.scrollTop = history.scrollHeight;
            }, 600);
        }

        function sendAIChip(txt) {
            document.getElementById('ai-input').value = txt;
            sendAIChat();
        }

