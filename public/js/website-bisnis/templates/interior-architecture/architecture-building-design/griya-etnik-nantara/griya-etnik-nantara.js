        // Cost Calculator
        function calculateCost() {
            const type = document.getElementById('calc-type').value;
            const wood = document.getElementById('calc-wood').value;
            const area = parseInt(document.getElementById('calc-area').value);

            document.getElementById('area-val').textContent = area + ' m²';

            let basePricePerM2 = 5500000; // default Limasan

            if (type === 'joglo') basePricePerM2 = 7500000;
            else if (type === 'gladak') basePricePerM2 = 4800000;
            else if (type === 'resort') basePricePerM2 = 6800000;

            if (wood === 'perhutani') basePricePerM2 *= 1.25;
            else if (wood === 'campuran') basePricePerM2 *= 0.85;

            const totalCost = basePricePerM2 * area;
            const formattedCost = new Intl.NumberFormat('id-ID', { style: 'currency', currency: 'IDR', maximumFractionDigits: 0 }).format(totalCost);

            document.getElementById('cost-result').textContent = formattedCost;
        }

