        let currentLang = 'id';

        function setLanguage(lang) {
            currentLang = lang;
            document.querySelectorAll('[data-i18n]').forEach(el => {
                const key = el.getAttribute('data-i18n');
                if (translations[lang] && translations[lang][key]) {
                    el.textContent = translations[lang][key];
                }
            });

            if (lang === 'id') {
                document.getElementById('lang-id').className = "px-2 py-0.5 rounded-full font-bold transition text-teak-950 bg-keratonGold-500 text-[11px]";
                document.getElementById('lang-en').className = "px-2 py-0.5 rounded-full font-bold transition text-teak-300 hover:text-white text-[11px]";
            } else {
                document.getElementById('lang-en').className = "px-2 py-0.5 rounded-full font-bold transition text-teak-950 bg-keratonGold-500 text-[11px]";
                document.getElementById('lang-id').className = "px-2 py-0.5 rounded-full font-bold transition text-teak-300 hover:text-white text-[11px]";
            }
        }

