        // --- LUMI AI CHATBOT INTERACTION ---
        function sendAIChat() {
            const input = document.getElementById('ai-input');
            const history = document.getElementById('ai-chat-history');
            const text = input.value.trim();

            if (!text) return;

            // Render User Bubble
            const userBubble = document.createElement('div');
            userBubble.className = "bg-gold-500 text-mint-950 font-medium p-3 rounded-xl max-w-[85%] ml-auto text-xs";
            userBubble.textContent = text;
            history.appendChild(userBubble);

            input.value = '';
            history.scrollTop = history.scrollHeight;

            // Generate AI Answer Response
            setTimeout(() => {
                const aiBubble = document.createElement('div');
                aiBubble.className = "bg-mint-900 p-3 rounded-xl border border-mint-800 text-mint-100 max-w-[85%] text-xs space-y-1";
                
                if (text.toLowerCase().includes('buku') || text.toLowerCase().includes('rekomendasi')) {
                    aiBubble.innerHTML = "Buku rekomendasi utama Aria Thorne saat ini adalah <strong>Whispers of the Emerald Canopy</strong> (fiksi spekulatif) dan <strong>Solitude & Modern Solace</strong> (esai filsafat). Mana genre yang paling Anda sukai?";
                } else if (text.toLowerCase().includes('event') || text.toLowerCase().includes('acara')) {
                    aiBubble.innerHTML = "Acara terdekat adalah <strong>Jakarta Book Fair</strong> pada 12 November 2026 di JCC Senayan (Grand Book Signing).";
                } else {
                    aiBubble.innerHTML = "Terima kasih telah menyapa! Saya Lumi siap membantu pertanyaan Anda mengenai naskah, pemesanan buku bertanda tangan, atau jadwal masterclass Aria Thorne.";
                }

                history.appendChild(aiBubble);
                history.scrollTop = history.scrollHeight;
            }, 600);
        }

        function sendQuickAIQuery(queryText) {
            document.getElementById('ai-input').value = queryText;
            sendAIChat();
        }

