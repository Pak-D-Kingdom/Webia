        let currentLang = 'id';

        function setLanguage(lang) {
            currentLang = lang;
            document.querySelectorAll('[data-i18n]').forEach(el => {
                const key = el.getAttribute('data-i18n');
                if (translations[lang] && translations[lang][key]) {
                    el.textContent = translations[lang][key];
                }
            });

            // Toggle active styling on language buttons
            if (lang === 'id') {
                document.getElementById('lang-id').className = "px-2 py-0.5 rounded-full font-bold transition-all text-mint-950 bg-mint-200 text-xs flex items-center gap-1";
                document.getElementById('lang-en').className = "px-2 py-0.5 rounded-full font-bold transition-all text-mint-300 hover:text-white text-xs flex items-center gap-1";
            } else {
                document.getElementById('lang-en').className = "px-2 py-0.5 rounded-full font-bold transition-all text-mint-950 bg-mint-200 text-xs flex items-center gap-1";
                document.getElementById('lang-id').className = "px-2 py-0.5 rounded-full font-bold transition-all text-mint-300 hover:text-white text-xs flex items-center gap-1";
            }
        }

