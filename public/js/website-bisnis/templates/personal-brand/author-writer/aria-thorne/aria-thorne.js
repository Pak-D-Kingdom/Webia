        let isAudioPlaying = false;
        function playAudioSnippet() {
            const audio = document.getElementById('hero-audio');
            const icon = document.getElementById('audio-icon');
            const statusText = document.getElementById('audio-status-text');

            if (!isAudioPlaying) {
                audio.play().then(() => {
                    isAudioPlaying = true;
                    icon.className = "fa-solid fa-pause text-xs";
                    statusText.textContent = "Memutar Audio Prolog... (Pause)";
                }).catch(() => {
                    alert("Audio file preview loading error.");
                });
            } else {
                audio.pause();
                isAudioPlaying = false;
                icon.className = "fa-solid fa-play text-xs";
                statusText.textContent = "Dengar Prolog Audio (1:15)";
            }
        }

