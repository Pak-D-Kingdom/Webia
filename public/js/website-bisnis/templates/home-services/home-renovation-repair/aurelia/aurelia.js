        // Hero Calculator Logic
        const heroAreaRange = document.getElementById('heroAreaRange');
        const heroAreaVal = document.getElementById('heroAreaVal');
        const heroPropType = document.getElementById('heroPropType');
        const heroScope = document.getElementById('heroScope');
        const heroEstimatedCost = document.getElementById('heroEstimatedCost');

        function updateHeroEstimate() {
            const sqM = parseInt(heroAreaRange.value);
            heroAreaVal.innerText = sqM.toLocaleString() + ' Sq M';
            
            const propMultiplier = parseFloat(heroPropType.value);
            const scopeBaseRate = parseFloat(heroScope.value);

            if (currentLang === 'id') {
                const baseCostRp = sqM * scopeBaseRate * propMultiplier * 1550000;
                const min = Math.round(baseCostRp * 0.9 / 100000000) / 10;
                const max = Math.round(baseCostRp * 1.15 / 100000000) / 10;
                heroEstimatedCost.innerText = `Rp ${min} M - Rp ${max} M`;
            } else {
                const baseCost = sqM * scopeBaseRate * propMultiplier * 100;
                const minCost = Math.round(baseCost * 0.9);
                const maxCost = Math.round(baseCost * 1.15);
                heroEstimatedCost.innerText = `$${minCost.toLocaleString()} - $${maxCost.toLocaleString()}`;
            }
        }

        heroAreaRange.addEventListener('input', updateHeroEstimate);
        heroPropType.addEventListener('change', updateHeroEstimate);
        heroScope.addEventListener('change', updateHeroEstimate);

